"""Spike 71: which constituent does a recurrent learner select? Head-to-head of three predictors computed
before training (predictive energy, C37; AGF utility, Kunin et al. 2025 / Marchetti et al. 2026 extrapolated;
minimum rho-set orbit size, Wu et al. 2025), with emergence order tracked over training and a
reparametrisation-invariant geometry check. Machinery from Spike 69 (frozen; imported). See SPIKE_71_REPORT.md."""
import itertools, json, os, sys
import numpy as np
from experiments.spike58 import comp, inv, cyc, closure
import experiments.spike69 as S

ROOT = os.path.dirname(os.path.abspath(__file__))
RAW = os.path.join(ROOT, "results", "spike71_raw")
OUT = os.path.join(ROOT, "results", "spike71.json")
PRED = os.path.join(ROOT, "results", "spike71_predictions.json")
SEEDS, STEPS, LEN, BATCH, HORIZON = 5, 6000, 30, 64, 30
CKPTS = list(range(50, 2001, 50)) + list(range(2500, STEPS + 1, 500))
ident = S.ident

S4g = [cyc(4, [0, 1]), cyc(4, [0, 1, 2, 3])]
A5g = [cyc(5, [0, 1, 2]), cyc(5, [0, 1, 2, 3, 4])]
D4g = [cyc(4, [0, 1, 2, 3]), cyc(4, [1, 3])]
A4g = [cyc(4, [0, 1, 2]), cyc(4, [0, 1], [2, 3])]
Zg = lambda n: [cyc(n, list(range(n)))]


def coset_out(gens, H):
    G = sorted(closure(gens)); Hs = closure(H) if H else {ident(len(gens[0]))}
    labels = sorted({frozenset(comp(g, h) for h in Hs) for g in G}, key=lambda s: sorted(s))
    lab = {g: labels.index(frozenset(comp(g, h) for h in Hs)) for g in G}
    return lambda x: tuple(int(lab[x] == i) for i in range(len(labels)))


def table():
    return {
        # coset readouts G/H
        "S4_12": (S4g, coset_out(S4g, [cyc(4, [0, 1])])),                       # H = <(01)>
        "S4_12b": (S4g, coset_out(S4g, [cyc(4, [0, 1], [2, 3])])),              # H = <(01)(23)> (Spike 62 readout, new letters below)
        "S4_8": (S4g, coset_out(S4g, [cyc(4, [0, 1, 2])])),                     # H = <(012)>
        "A5_10": (A5g, coset_out(A5g, [cyc(5, [0, 1, 2]), cyc(5, [0, 1], [3, 4])])),
        "A5_20": (A5g, coset_out(A5g, [cyc(5, [0, 1, 2])])),                    # C3, 20 cosets (Zhang & Li's stage)
        "D4_4r": (D4g, coset_out(D4g, [cyc(4, [0, 2])])),                       # H = <(02)> (vertex stabiliser)
        "D4_4e": (D4g, coset_out(D4g, [cyc(4, [0, 1], [2, 3])])),               # H = edge reflection
        "A4_4": (A4g, coset_out(A4g, [cyc(4, [1, 2, 3])])),                     # A4 on points
        # subset readouts of cyclic groups (cyclic 'smooth circle' cases)
        "Z11_03": (Zg(11), (lambda x: (int(x[0] in {0, 3}),))),
        "Z10_05": (Zg(10), (lambda x: (int(x[0] in {0, 5, 1}),))),
        "Z12_06": (Zg(12), (lambda x: (int(x[0] in {0, 6, 4}),))),
    }


def spec(name):
    g, out = table()[name]
    n = len(g[0]); G = sorted(closure(g))
    return G, g + [ident(n)], out


AUTOMATA = list(table().keys())


def _patch():
    S.spec = spec   # Spike 69's kernel/irrep code reads automata through S.spec


def minimal_states(name):
    G, L, out = spec(name)
    cls = {s: out(s) for s in G}
    while True:
        sig = {s: (cls[s],) + tuple(cls[comp(s, a)] for a in L) for s in G}
        ids = {v: i for i, v in enumerate(sorted(set(sig.values()), key=str))}
        new = {s: ids[sig[s]] for s in G}
        if len(set(new.values())) == len(set(cls.values())): return new
        cls = new


def subgroups(G):
    e = ident(len(G[0])); subs = {frozenset([e])}
    for a in G:
        subs.add(frozenset(closure([a])))
    for a, b in itertools.combinations(G, 2):
        subs.add(frozenset(closure([a, b])))
    return subs


def irrep_type(ir, G):
    """(n, C): complex dimension of one constituent and C = 2 for a merged conjugate pair, else 1."""
    idx = {g: i for i, g in enumerate(G)}; e = idx[ident(len(G[0]))]; N = len(G)
    psi = N * ir["P"][e]                                   # = n * (merged) character
    s = np.mean([psi[idx[comp(g, g)]] for g in G])        # n*FS indicator: +n real, -n quaternionic, 0 complex pair
    tr = ir["dim_real_sq"]
    if abs(s) > 0.5:
        n = int(round(np.sqrt(tr))); return n, 1
    n = int(round(np.sqrt(tr / 2))); return n, 2


def predictors(name):
    _patch()
    G, L, out = spec(name); N = len(G); idx = {g: i for i, g in enumerate(G)}
    _, Kc, _ = S.predictive_kernel(name); irs = S.real_irreps(G)
    labels = [S.irrep_label(ir, k) for k, ir in enumerate(irs)]
    wt = S.isotypic_weights(Kc, irs)
    O = np.array([out(g) for g in G], float)
    # module generated by the outputs: all LEFT translates g -> o(a g) (left cosets are permuted by left multiplication;
    # the two-sided isotypic block P_rho meets a left-invariant module in dimension mult * n * C)
    F = np.concatenate([O[[idx[comp(a, g)] for g in G]] for a in G], axis=1)
    F = F - F.mean(0)
    info = {}
    for k, ir in enumerate(irs):
        lab = labels[k]; n, C = irrep_type(ir, G)
        R = np.linalg.matrix_rank(ir["P"] @ F, tol=1e-6)
        m = R / (C * n)
        op2 = wt[lab] / (m ** 2 * C) if m > 0 else 0.0          # ||x_hat[rho]||_op^2 up to a common constant
        agf = (op2 ** 1.5) / np.sqrt(C * n) if m > 0 else 0.0     # k = 2 utility: ||x||^3 / (C n)^(1/2)
        info[lab] = {"n": n, "C": C, "mult": m, "energy": wt[lab], "agf": float(agf), "faithful": ir["faithful"], "kernel": ir["kernel_size"]}
    # minimum orbit size of a nonzero vector in each constituent present
    subs = subgroups(G)
    for k, ir in enumerate(irs):
        lab = labels[k]
        if info[lab]["mult"] == 0: info[lab]["min_orbit"] = None; continue
        best = None
        for K in subs:
            fix = np.mean([np.trace(ir["P"] @ np.eye(N)[:, [idx[comp(g, kk)] for g in G]]) for kk in K])
            if fix > 1e-6:
                ind = N // len(K); best = ind if best is None else min(best, ind)
        info[lab]["min_orbit"] = best
    present = [l for l in labels if info[l]["mult"] > 0 and info[l]["energy"] > 1e-3]
    top = lambda key, rev=True: sorted(present, key=lambda l: info[l][key], reverse=rev)
    def unique(order, key, rev=True, margin=1.5):
        a, b = info[order[0]][key], (info[order[1]][key] if len(order) > 1 else 0)
        if rev: return order[0] if (b == 0 or a >= margin * b) else None
        return order[0] if a * margin <= b or len(order) == 1 else None
    pe, pa, po = top("energy"), top("agf"), top("min_orbit", rev=False)
    amax = info[pa[0]]["agf"]; agf_set = [l for l in pa if info[l]["agf"] >= 0.98 * amax]
    omin = info[po[0]]["min_orbit"]; orb_set = [l for l in po if info[l]["min_orbit"] == omin]
    for k, ir in enumerate(irs): info[labels[k]]["smooth"] = S.smoothness(ir, G, L)
    return {"order": N, "minimal_states": len(set(minimal_states(name).values())), "irreps": info, "present": present,
            "pred_energy": unique(pe, "energy"), "pred_agf": agf_set, "pred_orbit": orb_set,
            "orders": {"energy": pe, "agf": pa, "orbit": po}}


def predict():
    res = {}
    for name in AUTOMATA:
        p = predictors(name); res[name] = p
        print(f"{name:7s} |G|={p['order']:3d} min={p['minimal_states']:3d} E={p['pred_energy']} AGF={p['pred_agf']} ORB={p['pred_orbit']}")
        print("        ", {l: (round(v['energy'], 2), round(v['agf'], 4), v['n'], v['C'], v['mult'], v['min_orbit']) for l, v in p["irreps"].items() if l in p["present"]})
    json.dump(res, open(PRED, "w"), indent=1)


def shares(C, irs):
    Gm = C @ C.T; Gm = Gm - Gm.mean(0) - Gm.mean(1)[:, None] + Gm.mean()
    w = np.array([np.sum((ir["P"] @ Gm @ ir["P"]) ** 2) for ir in irs]); return w / max(w.sum(), 1e-12)


def run_one(name, seed):
    import torch
    from experiments.spike60 import build
    _patch()
    torch.manual_seed(seed); rng = np.random.default_rng(seed)
    G, L, out = spec(name); e = ident(len(G[0])); k_out = len(out(e)); idx = {g: i for i, g in enumerate(G)}
    irs = S.real_irreps(G); labels = [S.irrep_label(ir, k) for k, ir in enumerate(irs)]
    def sample(B, T, r):
        X = r.integers(0, len(L), size=(B, T)); Y = np.zeros((B, T, k_out), np.float32); ST = np.zeros((B, T), int)
        for b in range(B):
            s = e
            for t in range(T):
                s = comp(s, L[X[b, t]]); Y[b, t] = out(s); ST[b, t] = idx[s]
        return X, Y, ST
    Xe, Ye, STe = sample(400, LEN, np.random.default_rng(seed + 2 * 10**6))
    m = build("gru", len(L), k_out)
    opt = torch.optim.Adam(m.parameters(), lr=0.003); sch = torch.optim.lr_scheduler.CosineAnnealingLR(opt, STEPS)
    traj = []
    def geometry():
        with torch.no_grad():
            H = m.hidden(torch.tensor(Xe)).numpy()
            acc = float(((m(torch.tensor(Xe)) > 0).float() == torch.tensor(Ye)).float().mean())
        flatH, flatL = H[:, 5:].reshape(-1, H.shape[2]), STe[:, 5:].ravel()
        Ce = np.stack([flatH[flatL == j].mean(0) for j in range(len(G))])
        C1 = Ce - Ce.mean(0); C1 = C1 / np.maximum(np.linalg.norm(C1, axis=1, keepdims=True), 1e-9)
        # reparametrisation-invariant version: whiten by the pooled within-element covariance
        R = flatH - Ce[flatL]; W = np.cov(R.T) + 1e-4 * np.eye(R.shape[1])
        ev, EV = np.linalg.eigh(W); Wm = EV @ np.diag(ev ** -0.5) @ EV.T
        C2 = (Ce - Ce.mean(0)) @ Wm
        return acc, shares(C1, irs), shares(C2, irs)
    for step in range(1, STEPS + 1):
        X, Y, _ = sample(BATCH, LEN, rng)
        loss = torch.nn.functional.binary_cross_entropy_with_logits(m(torch.tensor(X)), torch.tensor(Y))
        opt.zero_grad(); loss.backward(); opt.step(); sch.step()
        if step in CKPTS:
            acc, s1, s2 = geometry(); traj.append({"step": step, "acc": acc, "shares": s1.tolist(), "shares_white": s2.tolist()})
    r = {"automaton": name, "seed": seed, "labels": labels, "traj": traj}
    with torch.no_grad():
        X, Y, _ = sample(500, 100, np.random.default_rng(seed + 10**6))
        r["fit"] = float(((m(torch.tensor(X)) > 0).float() == torch.tensor(Y)).float().mean())
    final = traj[-1]
    r["final_leader"] = labels[int(np.argmax(final["shares"]))]
    r["final_leader_white"] = labels[int(np.argmax(final["shares_white"]))]
    reg = np.array([ir["dim_real_sq"] for ir in irs], float); reg = reg / reg.sum()
    first = None
    for t in traj:
        tau = 0.5 * np.abs(np.array(t["shares"]) - reg).sum()
        if tau >= 0.15: first = t; break
    r["first_step"] = first["step"] if first else None
    r["first_leader"] = labels[int(np.argmax(first["shares"]))] if first else None
    return r


def run(which=None):
    import torch
    torch.set_num_threads(2); os.makedirs(RAW, exist_ok=True)
    for name in (AUTOMATA if which is None else which.split(",")):
        for i in range(SEEDS):
            p = os.path.join(RAW, f"{name}_{i}.json")
            if os.path.exists(p): continue
            r = run_one(name, 7100 + 10 * AUTOMATA.index(name) + i)
            json.dump(r, open(p, "w"))
            print(name, i, round(r["fit"], 3), "first", r["first_step"], r["first_leader"], "final", r["final_leader"], "white", r["final_leader_white"], flush=True)


def analyse():
    P = json.load(open(PRED))
    runs = [json.load(open(os.path.join(RAW, f"{n}_{i}.json"))) for n in AUTOMATA for i in range(SEEDS) if os.path.exists(os.path.join(RAW, f"{n}_{i}.json"))]
    fit = [r for r in runs if r["fit"] >= 0.99]
    nfit = {n: sum(r["automaton"] == n for r in fit) for n in AUTOMATA}
    ok = [r for r in fit if nfit[r["automaton"]] >= 3]
    tri = lambda f, hi, lo: "NO VERDICT" if f is None else "HELD" if f >= hi else "BROKEN" if f < lo else "NEITHER"
    frac = lambda xs: float(np.mean(xs)) if xs else None
    def hit(pred, x):
        return x in pred if isinstance(pred, list) else x == pred
    def test(key, which):
        rs = [r for r in ok if P[r["automaton"]][key]]
        return frac([hit(P[r["automaton"]][key], r[which]) for r in rs]), len({r["automaton"] for r in rs})
    fE, nE = test("pred_energy", "final_leader"); fA, nA = test("pred_agf", "first_leader"); fO, nO = test("pred_orbit", "final_leader")
    fAf, _ = test("pred_agf", "final_leader")
    # discriminating subset: energy and AGF disagree (both defined)
    dis = [r for r in ok if P[r["automaton"]]["pred_energy"] and P[r["automaton"]]["pred_energy"] not in P[r["automaton"]]["pred_agf"]]
    fD = frac([r["final_leader"] == P[r["automaton"]]["pred_energy"] for r in dis]); fDa = frac([r["final_leader"] in P[r["automaton"]]["pred_agf"] for r in dis])
    ties = [r for r in ok if not P[r["automaton"]]["pred_energy"]]
    fT = frac([r["final_leader"] in P[r["automaton"]]["pred_agf"] for r in ties])
    def smooth_faithful(n):
        I = P[n]["irreps"]; f = [l for l, v in I.items() if v["faithful"]]
        return max(f, key=lambda l: I[l]["smooth"]) if f else None
    cyc_rs = [r for r in ok if r["automaton"].startswith("Z") and P[r["automaton"]]["pred_energy"] != smooth_faithful(r["automaton"])]
    fC = frac([r["final_leader"] == P[r["automaton"]]["pred_energy"] for r in cyc_rs]); fCs = frac([r["final_leader"] == smooth_faithful(r["automaton"]) for r in cyc_rs])
    per = [r for r in ok if r["first_leader"]]
    fP = frac([r["first_leader"] == r["final_leader"] for r in per])
    fW = frac([r["final_leader_white"] == r["final_leader"] for r in ok])
    v = {"H71.1": tri(fE, 0.8, 0.5) if nE >= 4 else "NO VERDICT",
         "H71.2": tri(fA, 0.8, 0.5) if nA >= 4 else "NO VERDICT",
         "H71.3": tri(fO, 0.8, 0.5) if nO >= 4 else "NO VERDICT",
         "H71.4": ("NO VERDICT" if len({r['automaton'] for r in dis}) < 2 else "HELD" if fD >= 0.8 else "BROKEN" if fDa >= 0.5 else "NEITHER"),
         "H71.5": tri(fP, 0.8, 0.5) if per else "NO VERDICT",
         "H71.6": tri(fW, 0.8, 0.5) if ok else "NO VERDICT",
         "H71.7": tri(fT, 0.8, 0.5) if len({r['automaton'] for r in ties}) >= 2 else "NO VERDICT",
         "H71.8": ("NO VERDICT" if len({r['automaton'] for r in cyc_rs}) < 2 else "HELD" if fC >= 0.8 else "BROKEN" if fCs >= 0.5 else "NEITHER")}
    pa = {}
    for n in AUTOMATA:
        rs = [r for r in fit if r["automaton"] == n]
        pa[n] = {"fitted": len(rs), "fits": [round(r["fit"], 3) for r in runs if r["automaton"] == n],
                 "pred": {k: P[n][k] for k in ("pred_energy", "pred_agf", "pred_orbit")},
                 "first": [r["first_leader"] for r in rs], "first_step": [r["first_step"] for r in rs],
                 "final": [r["final_leader"] for r in rs], "final_white": [r["final_leader_white"] for r in rs]}
    out = {"verdicts": v, "frac": {"energy_final": fE, "agf_first": fA, "agf_final": fAf, "orbit_final": fO, "discrim_energy": fD,
           "discrim_agf": fDa, "persist": fP, "white_agree": fW, "ties_lowdim": fT, "cyclic_energy": fC, "cyclic_smooth": fCs}, "per_automaton": pa}
    json.dump(out, open(OUT, "w"), indent=1); print(json.dumps(v, indent=1)); print(json.dumps(out["frac"], indent=1))
    for n, x in pa.items(): print(n, x["fitted"], x["pred"], "first", x["first"], "final", x["final"])


if __name__ == "__main__":
    c = sys.argv[1]
    if c == "run": run(sys.argv[2] if len(sys.argv) > 2 else None)
    else: {"predict": predict, "analyse": analyse}[c]()
