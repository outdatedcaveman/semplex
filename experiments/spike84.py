"""Spike 84: the head of the observable module. For an automaton, the inputs act on observables by (T_a f)(q) =
f(delta_a q); they generate a matrix algebra A. Its Jacobson radical rad(A) is computed exactly (Dickson: in
characteristic 0, x in rad(A) iff tr(x y) = 0 for all y in A). The observable module O = span{T_w o} (Krylov space of
the output); its radical layer R = rad(A)·O; its HEAD = the pi-orthogonal complement of R in O (constants removed).
For groups rad(A) = 0 and the head is all of O. Conjecture: learners concentrate their geometry in the head.
See SPIKE_84_REPORT.md."""
import json, os, sys
import numpy as np
import experiments.spike81 as S81

ROOT = os.path.dirname(os.path.abspath(__file__))
RAW = os.path.join(ROOT, "results", "spike84_raw")
OUT = os.path.join(ROOT, "results", "spike84.json")
PRED = os.path.join(ROOT, "results", "spike84_predictions.json")


def ops(Dl):
    m = Dl.shape[1]; return [np.eye(m)[Dl[a]] for a in range(Dl.shape[0])]       # (T f)(q) = f(delta(q)) -> T = P_delta


def algebra(T, tol=1e-9):
    """basis of the matrix algebra generated by the T_a (with identity)"""
    m = T[0].shape[0]; basis = [np.eye(m)]; vecs = np.eye(m).reshape(1, -1); frontier = [np.eye(m)]
    def add(M):
        nonlocal vecs
        v = M.reshape(1, -1); X = np.vstack([vecs, v])
        if np.linalg.matrix_rank(X, tol) > vecs.shape[0]: vecs = X; basis.append(M); return True
        return False
    while frontier:
        new = []
        for M in frontier:
            for t in T:
                P = M @ t
                if add(P): new.append(P)
        frontier = new
    return basis


def radical(basis, tol=1e-8):
    B = len(basis); Gm = np.array([[np.trace(x @ y) for y in basis] for x in basis])
    w, V = np.linalg.eigh((Gm + Gm.T) / 2); null = V[:, np.abs(w) < tol * max(1, np.abs(w).max())]
    return [sum(c * b for c, b in zip(col, basis)) for col in null.T]


def span(vs, tol=1e-9):
    if not vs: return np.zeros((len(vs[0]) if vs else 0, 0))
    M = np.column_stack(vs); U, s, _ = np.linalg.svd(M, full_matrices=False); return U[:, s > tol * max(s.max(), 1e-12)]


def head_structure(Dl, O, pi):
    m = Dl.shape[1]; T = ops(Dl); A = algebra(T); R = radical(A)
    W = np.sqrt(pi); one = W / np.linalg.norm(W)
    def to_w(v): x = W * v; return x - one * (one @ x)                             # sqrt(pi)-frame, constants removed
    # observable module: Krylov space of the output under the algebra
    Ov = span([to_w(b @ O.astype(float)) for b in A])
    Rv = span([to_w(r @ (b @ O.astype(float))) for r in R for b in A]) if R else np.zeros((m, 0))
    if Rv.shape[1]:
        Rv = Ov @ (Ov.T @ Rv); Rv = span([Rv[:, j] for j in range(Rv.shape[1])]) if np.linalg.norm(Rv) > 1e-9 else np.zeros((m, 0))
    Hp = Ov - (Rv @ (Rv.T @ Ov) if Rv.shape[1] else 0); Hv = span([Hp[:, j] for j in range(Hp.shape[1])]) if np.linalg.norm(Hp) > 1e-9 else np.zeros((m, 0))
    return {"dimA": len(A), "dimRad": len(R), "dimO": Ov.shape[1], "dimR": Rv.shape[1], "dimH": Hv.shape[1], "H": Hv.tolist(), "R": Rv.tolist(), "O": Ov.tolist()}


def predict():
    P81 = json.load(open(S81.PRED)); pool = S81.build_pool(); rows = []
    for i, A in enumerate(pool):
        D, O = np.array(A["D"]), np.array(A["O"]); Dl = np.vstack([D, np.arange(D.shape[1])[None]]); k = Dl.shape[0]
        pi = S81.visit_dist(Dl, A["s0"], np.ones(k) / k)
        if (pi <= 1e-6).any(): continue                                        # avoid unvisited states (Spike 83 bug)
        hs = head_structure(Dl, O, pi)
        if hs["dimR"] >= 1 and hs["dimH"] >= 1: rows.append({"id": i, **A, "pi": pi.tolist(), **hs})
    rng = np.random.default_rng(84); pick = [rows[j] for j in rng.choice(len(rows), size=min(16, len(rows)), replace=False)]
    json.dump({"automata": pick, "n_pool": len(pool), "n_nontrivial": len(rows)}, open(PRED, "w"))
    from collections import Counter
    print("pool", len(pool), "with nontrivial radical layer and head:", len(rows), "picked", len(pick), Counter(r["kind"] for r in pick))
    for r in pick: print(r["id"], r["kind"], "dimO", r["dimO"], "dimH", r["dimH"], "dimR", r["dimR"], "head fraction", round(r["dimH"] / r["dimO"], 2))


_POOL = []
def _pool():
    if not _POOL: _POOL.extend(S81.build_pool())
    return _POOL


def train(A, seed):
    import torch
    from experiments.spike60 import build
    nn = torch.nn
    src = _pool()[A["id"]]; assert src["D"] == A["D"]                            # bug fix: A["O"] holds the module basis (key clash)
    D, O = np.array(A["D"]), np.array(src["O"]); Dl = np.vstack([D, np.arange(D.shape[1])[None]]); m = Dl.shape[1]; L = Dl.shape[0]
    torch.manual_seed(seed); rng = np.random.default_rng(seed)
    def sample(B, T, r):
        X = r.integers(0, L, size=(B, T)); Y = np.zeros((B, T, 1), np.float32); ST = np.zeros((B, T), int)
        for b in range(B):
            q = A["s0"]
            for t in range(T): q = Dl[X[b, t]][q]; Y[b, t, 0] = O[q]; ST[b, t] = q
        return X, Y, ST
    mdl = build("gru", L, 1); opt = torch.optim.Adam(mdl.parameters(), lr=0.003); sch = torch.optim.lr_scheduler.CosineAnnealingLR(opt, 6000)
    for _ in range(6000):
        X, Y, _ = sample(64, 30, rng)
        loss = nn.functional.binary_cross_entropy_with_logits(mdl(torch.tensor(X)), torch.tensor(Y)); opt.zero_grad(); loss.backward(); opt.step(); sch.step()
    with torch.no_grad():
        X, Y, _ = sample(500, 100, np.random.default_rng(seed + 10**6)); fit = float(((mdl(torch.tensor(X)) > 0).float() == torch.tensor(Y)).float().mean())
        X, Y, ST = sample(400, 30, np.random.default_rng(seed + 2 * 10**6)); H = mdl.hidden(torch.tensor(X)).numpy()
    flatH, flatL = H[:, 5:].reshape(-1, 64), ST[:, 5:].ravel()
    Ce = np.stack([flatH[flatL == q].mean(0) if (flatL == q).any() else np.full(64, np.nan) for q in range(m)])
    return fit, Ce


def measure(A, Ce):
    pi = np.array(A["pi"]); W = np.sqrt(pi); one = W / np.linalg.norm(W)
    if np.isnan(Ce).any(): return None
    mu = (pi[:, None] * Ce).sum(0); X = W[:, None] * (Ce - mu)                     # sqrt(pi)-weighted centred centroids (m x 64)
    X = X - np.outer(one, one @ X)
    tot = np.sum(X * X); Hv, Rv, Ov = np.array(A["H"]), np.array(A["R"]), np.array(A["O"])
    proj = lambda U: float(np.sum((U.T @ X) ** 2) / tot) if U.size else 0.0
    sH, sR, sO = proj(Hv), proj(Rv), proj(Ov)
    U, s, _ = np.linalg.svd(X, full_matrices=False); u1 = U[:, 0]
    top_H = float(np.sum((Hv.T @ u1) ** 2)) if Hv.size else 0.0; top_R = float(np.sum((Rv.T @ u1) ** 2)) if Rv.size else 0.0
    return {"share_head": sH, "share_rad": sR, "share_obs": sO, "head_dim_frac": A["dimH"] / A["dimO"],
            "top_in_head": top_H, "top_in_rad": top_R}


def run():
    import torch
    torch.set_num_threads(2); os.makedirs(RAW, exist_ok=True); P = json.load(open(PRED))
    for A in P["automata"]:
        for i in range(3):
            pth = os.path.join(RAW, f"{A['id']}_{i}.json")
            if os.path.exists(pth): continue
            fit, Ce = train(A, 8400 + 10 * A["id"] + i); r = {"id": A["id"], "kind": A["kind"], "fit": fit, "res": measure(A, Ce)}
            np.save(os.path.join(RAW, f"{A['id']}_{i}_centroids.npy"), Ce)
            json.dump(r, open(pth, "w")); print(A["id"], A["kind"], i, round(fit, 3), r["res"] and {k: round(v, 3) for k, v in r["res"].items()}, flush=True)


def analyse():
    runs = [json.load(open(os.path.join(RAW, f))) for f in sorted(os.listdir(RAW)) if f.endswith(".json")]
    ok = [r for r in runs if r["fit"] >= 0.99 and r["res"]]
    frac = lambda xs: float(np.mean(xs)) if xs else None
    f1 = frac([r["res"]["share_head"] / max(r["res"]["share_obs"], 1e-12) > r["res"]["head_dim_frac"] for r in ok])
    f2 = frac([r["res"]["top_in_head"] > r["res"]["top_in_rad"] for r in ok])
    f3 = frac([r["res"]["share_obs"] >= 0.8 for r in ok])
    tri = lambda f, hi, lo: "NO VERDICT" if f is None or len({r['id'] for r in ok}) < 6 else "HELD" if f >= hi else "BROKEN" if f < lo else "NEITHER"
    v = {"H84.1": tri(f1, 0.8, 0.5), "H84.2": tri(f2, 0.7, 0.5), "H84.3": tri(f3, 0.8, 0.5)}
    med = lambda k: float(np.median([r["res"][k] for r in ok])) if ok else None
    out = {"verdicts": v, "frac": {"head_over_dimension": f1, "top_in_head": f2, "geometry_in_observable": f3},
           "median": {k: med(k) for k in ("share_head", "share_rad", "share_obs", "head_dim_frac", "top_in_head", "top_in_rad")},
           "n_runs": len(ok), "n_automata": len({r['id'] for r in ok})}
    json.dump(out, open(OUT, "w"), indent=1); print(json.dumps(out, indent=1))


if __name__ == "__main__":
    {"predict": predict, "run": run, "analyse": analyse}[sys.argv[1]]()
